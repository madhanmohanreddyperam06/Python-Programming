## variable names in different cases

# pascal case -> each word starts with an uppercase letter
MySchoolName = "SVHS"
print(MySchoolName)

# camel case -> each word starts with an uppercase letter except 1st word
mySchoolName = "SVHS"
print(mySchoolName)

# snake case -> each word is separated with an underscore (_)
my_school_name = "SVHS"
print(my_school_name)