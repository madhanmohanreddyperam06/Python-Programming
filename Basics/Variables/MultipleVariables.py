# Assigning multiple variables 

# Many-To-Many
x, y, z = "Apple", "Banana", "Cherry"
a, b, c = 1, 2, 3
print(x)
print(y)
print(z)
print(a)
print(b)
print(c)

# One-To-Many

k = l = m = "Apple"
print(k)    
print(l)
print(m)

# unpack a collection

fruits = ["Apple", "Banana", "Cherry"]
d,e,f = fruits
print(d)
print(e)
print(f)


